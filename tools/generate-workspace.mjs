import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createProjects, targets } from './topology.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const config = JSON.parse(await readFile(path.join(root, 'workspace.config.json'), 'utf8'));
const projects = createProjects(config);
const byName = new Map(projects.map((p) => [p.name, p]));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Usage: generate-workspace.mjs [--check]');
const json = (value) => JSON.stringify(value, null, 2) + '\n';
const relative = (from, to) => {
  const result = path.posix.relative(from, to);
  return result.startsWith('.') ? result : `./${result}`;
};
const files = new Map();
for (const project of projects) {
  const { name, dependencies, ownWeight } = project;
  const projectTargets = Object.fromEntries([...targets, ...(project.layer === 'e2e' ? ['e2e'] : [])].map((target) => [target, {
    executor: 'nx:run-commands',
    options: { command: `node tools/task.mjs ${target} ${project.root}` },
  }]));
  files.set(`${project.root}/project.json`, json({
    name, $schema: relative(project.root, 'node_modules/nx/schemas/project-schema.json'),
    projectType: project.application ? 'application' : 'library', sourceRoot: `${project.root}/src`,
    tags: [`scope:${project.scope}`, `layer:${project.layer}`, 'fixture:generated'],
    targets: projectTargets,
  }));
  files.set(`${project.root}/schema.json`, json({ name, ownWeight, dependencies }));
  files.set(`${project.root}/tsconfig.json`, json({
    extends: relative(project.root, 'tsconfig.base.json'), include: ['src/**/*.ts'],
  }));
  const imports = dependencies.map((dependency, i) => `import { weight as weight${i} } from '${relative(`${project.root}/src`, `${byName.get(dependency).root}/src/index.js`)}';`).join('\n');
  files.set(`${project.root}/src/index.ts`, `// Generated by tools/generate-workspace.mjs. Edit freely for affected/cache experiments.\n${imports}${imports ? '\n\n' : ''}export const projectName = '${name}';\nexport const weight: number = ${ownWeight}${dependencies.map((_, i) => ` + weight${i}`).join('')};\nexport const dependencies: readonly string[] = ${JSON.stringify(dependencies)};\n\nexport function evaluate(seed: number = 1): { project: string; value: number; dependencies: readonly string[] } {\n  if (!Number.isFinite(seed)) throw new TypeError('seed must be finite');\n  return { project: projectName, value: seed + weight, dependencies };\n}\n`);
  const builtImport = relative(`${project.root}/tests`, `dist/build/${name}/index.js`);
  files.set(`${project.root}/tests/index.test.mjs`, `// Generated, deterministic fixtures; these assertions really execute the compiled bundle.\nimport assert from 'node:assert/strict';\nimport { test } from 'node:test';\nimport { evaluate, weight, buildMetadata } from '${builtImport}';\n\ntest('${name}: dependency-derived value', () => {\n  assert.equal(weight, ${project.weight});\n  assert.deepEqual(evaluate(7), { project: '${name}', value: ${project.weight + 7}, dependencies: ${JSON.stringify(dependencies)} });\n});\n\ntest('${name}: default and negative seeds', () => {\n  assert.equal(evaluate().value, ${project.weight + 1});\n  assert.equal(evaluate(-7).value, ${project.weight - 7});\n});\n\ntest('${name}: rejects invalid input', () => {\n  for (const seed of [NaN, Infinity, -Infinity]) assert.throws(() => evaluate(seed), TypeError);\n});\n\ntest('${name}: generated build metadata', () => {\n  assert.equal(buildMetadata.name, '${name}');\n  assert.deepEqual(buildMetadata.dependencies, ${JSON.stringify(dependencies)});\n});\n`);
}
files.set('tools/generated/projects.json', json(projects));

// Never silently delete obsolete projects when a smaller topology is requested.
for (const directory of ['apps', 'libs', 'e2e']) {
  let entries;
  try { entries = await readdir(path.join(root, directory), { recursive: true }); }
  catch (error) { if (error.code === 'ENOENT') continue; throw error; }
  for (const entry of entries) {
    const file = `${directory}/${entry.split(path.sep).join('/')}`;
    if (file.endsWith('/project.json') && !files.has(file)) {
      throw new Error(`Obsolete project ${file}. Move or remove it explicitly before regenerating; no files were changed.`);
    }
  }
}
const drift = [];
for (const [file, content] of files) {
  let previous;
  try { previous = await readFile(path.join(root, file), 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previous === content) continue;
  drift.push(file);
  if (!check) {
    await mkdir(path.dirname(path.join(root, file)), { recursive: true });
    await writeFile(path.join(root, file), content);
  }
}
if (check && drift.length) {
  console.error(`Generated files differ (${drift.length}):\n${drift.slice(0, 20).join('\n')}\nRun pnpm generate to reset generated fixtures.`);
  process.exitCode = 1;
} else {
  console.log(`${check ? 'Checked' : 'Generated'} ${projects.length} projects, ${projects.reduce((sum, p) => sum + p.dependencies.length, 0)} import edges, ${files.size} files (${drift.length} changed).`);
}
